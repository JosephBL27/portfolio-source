//
//   FONT_GLSL   put once near the top of a reel's frag (after the uniforms). Defines
//               float fText(vec2 q, vec4 s, float n, float sc)
//                 q  = position in font pixels from the string's bottom-left (x right, y up);
//                      one glyph is 5 wide x 7 tall with a 6 pixel advance
