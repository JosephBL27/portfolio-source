const ALPHABET = Object.keys(ART)
const B = ALPHABET.length

export const C = (ch: string): string => {
  const i = ALPHABET.indexOf(ch)
  if (i < 0) throw new Error(`font: no glyph for "${ch}"`)
  return i.toFixed(1)
}
export const W = (s: string): number => s.length * 6 - 1
/** `vec4(...), n` for a string of up to 12 characters (3 per component, base-B digits). */
export const T = (s: string): string => {
  if (s.length > 12) throw new Error(`font: "${s}" is longer than 12 characters`)
  const v = [0, 0, 0, 0]
  for (let i = 0; i < s.length; i++) v[Math.floor(i / 3)] += ALPHABET.indexOf(s[i]) * Math.pow(B, i % 3)
  return `vec4(${v.map(x => x.toFixed(1)).join(', ')}), ${s.length.toFixed(1)}`
}

// glyph -> two packed floats: rows 0..3 as base-32 digits in x, rows 4..6 in y
function packed(ch: string): [number, number] {
  const rows = ART[ch].map(r => r.split('').reduce((a, c, k) => a + (c === '#' ? 1 << k : 0), 0))
  const lo = rows[0] + rows[1] * 32 + rows[2] * 1024 + rows[3] * 32768
  const hi = rows[4] + rows[5] * 32 + rows[6] * 1024
  return [lo, hi]
}
function tree(lo: number, hi: number, ind: string): string {
  if (hi - lo === 1) { const [a, b] = packed(ALPHABET[lo]); return `${ind}return vec2(${a.toFixed(1)}, ${b.toFixed(1)});\n` }
  const mid = (lo + hi) >> 1
  return `${ind}if (c < ${(mid - 0.5).toFixed(1)}) {\n${tree(lo, mid, ind + '  ')}${ind}} else {\n${tree(mid, hi, ind + '  ')}${ind}}\n`
}

export const FONT_GLSL = /* glsl */ `
vec2 fGlyphBits(float c) {
${tree(0, B, '  ')}}
float fCode(vec4 s, float i) {
  float comp = i < 2.5 ? s.x : (i < 5.5 ? s.y : (i < 8.5 ? s.z : s.w));
  float k = i - 3.0 * floor(i / 3.0);
  float pw = k < 0.5 ? 1.0 : (k < 1.5 ? ${B.toFixed(1)} : ${(B * B).toFixed(1)});
  return mod(floor((comp + 0.5) / pw), ${B.toFixed(1)});
}
// one glyph; g in font pixels, x 0..5, y 0..7 (up). Lit pixels are soft rounded dots.
float fChar(vec2 g, float code, float sc) {
  vec2 cell = floor(g);
  if (cell.x < 0.0 || cell.x > 4.0 || cell.y < 0.0 || cell.y > 6.0) return 0.0;
  float cy = 6.0 - cell.y;
  vec2 bits = fGlyphBits(code);
  float f = cy < 3.5 ? bits.x : bits.y;
  float rk = cy < 3.5 ? cy : cy - 4.0;
  float pw = rk < 0.5 ? 1.0 : (rk < 1.5 ? 32.0 : (rk < 2.5 ? 1024.0 : 32768.0));
  float row = mod(floor((f + 0.5) / pw), 32.0);
  float bp = cell.x < 0.5 ? 1.0 : (cell.x < 1.5 ? 2.0 : (cell.x < 2.5 ? 4.0 : (cell.x < 3.5 ? 8.0 : 16.0)));
  float on = mod(floor((row + 0.5) / bp), 2.0);
  if (on < 0.5) return 0.0;
  vec2 d = abs(g - cell - 0.5) - 0.33;
  float sd = length(max(d, 0.0)) + min(max(d.x, d.y), 0.0) - 0.12;
  return clamp(0.5 - sd * sc, 0.0, 1.0);
}
float fText(vec2 q, vec4 s, float n, float sc) {
  float i = floor(q.x / 6.0);
  if (i < 0.0 || i >= n || q.y < -0.6 || q.y > 7.6) return 0.0;
  return fChar(vec2(q.x - i * 6.0, q.y), fCode(s, i), sc);
}
`
